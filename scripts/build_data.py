#!/usr/bin/env python3
"""Build the dashboard data bundle from the look-ahead email thread.

Reads:
  source/*.eml               the daily "Loop test daily Look Ahead" thread
  data/daily_reports.json    daily KPI figures transcribed from each report

Writes:
  data/loop_register.json    loop/signal lists parsed from the email tables
  data/data.js               window.LOOPS_DATA bundle loaded by index.html

Usage: python3 scripts/build_data.py [path/to/thread.eml]
"""
import email
import glob
import json
import os
import sys
from email import policy

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IO_TYPES = {"AI", "AO", "DI", "DO"}
GROUPS = {"ACS", "HACCS"}


def plain_text(path):
    with open(path, "rb") as f:
        msg = email.message_from_binary_file(f, policy=policy.default)
    for part in msg.walk():
        if part.get_content_type() == "text/plain":
            return part.get_content()
    raise SystemExit(f"No text/plain part in {path}")


def split_reports(lines):
    """Yield (sent_line, body_lines) for each message in the quoted thread."""
    starts = [0] + [i for i, l in enumerate(lines) if l.startswith("Sent:")]
    for n, s in enumerate(starts):
        end = starts[n + 1] if n + 1 < len(starts) else len(lines)
        yield (lines[s] if s else "Sent: latest"), lines[s:end]


def parse_lists(lines):
    """Parse the two table shapes used in the thread.

    9-column rows (9 Oct): System, Comm Pkg, MC Pkg, Tag, Signal, Loop, RIO, RFCC, I/O
    7-column rows (12 Oct): Group, System, Comm Pkg, MC Pkg, Tag, Signal, Loop
    """
    rows, i = [], 0
    while i < len(lines):
        cell = lines[i]
        if cell in GROUPS and i + 6 < len(lines) and lines[i + 1].startswith("System"):
            g, s, c, m, t, sig, loop = lines[i:i + 7]
            rows.append(dict(group=g, system=s, comm=c, mc=m, tag=t, signal=sig, loop=loop))
            i += 7
        elif cell.startswith("System ") and "–" in cell and i + 8 < len(lines) and lines[i + 8] in IO_TYPES:
            s, c, m, t, sig, loop, rio, rfcc, io = lines[i:i + 9]
            rows.append(dict(system=s, comm=c, mc=m, tag=t, signal=sig, loop=loop, rio=rio, rfcc=rfcc, io=io))
            i += 9
        else:
            i += 1
    return rows


def main():
    eml = sys.argv[1] if len(sys.argv) > 1 else sorted(glob.glob(os.path.join(ROOT, "source", "*.eml")))[-1]
    lines = [l.strip() for l in plain_text(eml).split("\n")]

    lists = []
    for sent, body in split_reports(lines):
        rows = parse_lists(body)
        if rows:
            lists.append({"sent": sent.replace("Sent:", "").strip(), "rows": rows})

    register = {"source": os.path.relpath(eml, ROOT), "lists": lists}
    with open(os.path.join(ROOT, "data", "loop_register.json"), "w") as f:
        json.dump(register, f, indent=1, ensure_ascii=False)

    with open(os.path.join(ROOT, "data", "daily_reports.json")) as f:
        daily = json.load(f)
    daily["register"] = lists
    with open(os.path.join(ROOT, "data", "data.js"), "w") as f:
        f.write("// Generated by scripts/build_data.py. Do not edit by hand.\n")
        f.write("window.LOOPS_DATA = ")
        json.dump(daily, f, ensure_ascii=False)
        f.write(";\n")

    for l in lists:
        print(f"{l['sent']}: {len(l['rows'])} rows")


if __name__ == "__main__":
    main()
